/*
 * The two decisions the Android Keystore provider makes from what the keystore reports: where a key
 * it just generated or reattached actually lives, and whether a refused StrongBox generation may be
 * retried in the TEE. Both are pure functions of plain values so they are tested off-device; the
 * provider only reads the values (KeyInfo, the exception chain) and acts on the answer.
 */

/**
 * Where the keystore says one key lives, from its `KeyInfo`. This is the keystore's own report; only key attestation,
 * verified off the device, proves where a key lives.
 */
internal sealed interface KeystorePlacement {
    /** A TEE or StrongBox key: [custody] is what the key reports, never what was requested. */
    data class SecureHardware(
        val custody: KeyCustody.NonExportable.Hardware,
    ) : KeystorePlacement

    /**
     * Software ([offered] names it), or a level the keystore will not name (`SECURITY_LEVEL_UNKNOWN`, offered as
     * [OfferedCustody.Unreported]). Never handed out as hardware.
     */
    data class NotSecureHardware(
        val offered: OfferedCustody,
    ) : KeystorePlacement
}

/**
 * API 31+: the placement a `KeyInfo.getSecurityLevel()` value names. `SECURITY_LEVEL_UNKNOWN_SECURE` is secure
 * hardware whose kind the keystore does not say, so it counts at the TEE floor.
 */
internal fun placementOfSecurityLevel(securityLevel: Int): KeystorePlacement =
    when (securityLevel) {
        KeyProperties.SECURITY_LEVEL_STRONGBOX ->
            KeystorePlacement.SecureHardware(KeyCustody.NonExportable.Hardware(dedicatedSecureElement = true))
        KeyProperties.SECURITY_LEVEL_TRUSTED_ENVIRONMENT, KeyProperties.SECURITY_LEVEL_UNKNOWN_SECURE ->
            KeystorePlacement.SecureHardware(KeyCustody.NonExportable.Hardware(dedicatedSecureElement = false))
        KeyProperties.SECURITY_LEVEL_SOFTWARE -> keystoreSoftware
        else -> KeystorePlacement.NotSecureHardware(OfferedCustody.Unreported)
    }

/** A keystore key outside secure hardware: never exportable, but software. */
private val keystoreSoftware =
    KeystorePlacement.NotSecureHardware(OfferedCustody.Tier(CustodyTier.NonExportableSoftware))

/**
 * Pre-31, where `KeyInfo` exposes only `isInsideSecureHardware()`. A StrongBox request can be served in the TEE without
 * a word, and nothing before API 31 tells the two apart, so a secure key counts at the TEE floor.
 */
internal fun placementOfLegacyKeyInfo(insideSecureHardware: Boolean): KeystorePlacement =
    if (insideSecureHardware) {
        KeystorePlacement.SecureHardware(KeyCustody.NonExportable.Hardware(dedicatedSecureElement = false))
    } else {
        keystoreSoftware
    }

/** How the key whose placement is being judged came to be held. */
internal sealed interface KeyOrigin {
    /**
     * Generated by this call: nobody else holds it yet, so a key in the wrong place is deleted. [fallback] is what the
     * generation recorded about StrongBox.
     */
    data class JustGenerated(
        val fallback: SecureElementFallback,
    ) : KeyOrigin

    /** Persisted earlier and reattached: it is never deleted, and its fallback was never recorded. */
    data object Reattached : KeyOrigin
}

/** What to do with a key once its placement is known. */
internal sealed interface CustodyVerdict {
    data class Accept(
        val placement: KeyPlacement,
    ) : CustodyVerdict

    /** A key just generated outside secure hardware: delete it, then refuse. */
    data class DeleteAndRefuse(
        val offered: OfferedCustody,
    ) : CustodyVerdict
}

/**
 * A key in secure hardware is accepted with the custody its `KeyInfo` names. A key outside it is refused and deleted
 * when this call just generated it; a key persisted earlier (an earlier release did not check) is handed out with the
 * custody it really has, [KeyCustody.NonExportable.Software]: the keystore never exports it, and nothing vouches for
 * hardware. Refusing it would leave a stored key that no call could ever use; a caller that needs hardware checks the
 * key's own custody.
 */
internal fun custodyVerdict(
    placement: KeystorePlacement,
    origin: KeyOrigin,
): CustodyVerdict =
    when (placement) {
        is KeystorePlacement.SecureHardware ->
            CustodyVerdict.Accept(
                KeyPlacement(
                    placement.custody,
                    when (origin) {
                        is KeyOrigin.JustGenerated -> origin.fallback
                        KeyOrigin.Reattached -> SecureElementFallback.NotRecorded
                    },
                ),
            )
        is KeystorePlacement.NotSecureHardware ->
            when (origin) {
                is KeyOrigin.JustGenerated -> CustodyVerdict.DeleteAndRefuse(placement.offered)
                KeyOrigin.Reattached ->
                    CustodyVerdict.Accept(KeyPlacement(KeyCustody.NonExportable.Software, SecureElementFallback.NotRecorded))
            }
    }

/** The refusal of a key of [alg] that a generation placed outside secure hardware, as [offered]. */
internal fun notHardware(
    alg: ProtectedKeyAlgorithm,
    offered: OfferedCustody,
): InsufficientKeyCustody = InsufficientKeyCustody(alg = alg, required = CustodyTier.Hardware, offered = offered)

/** One link of a keystore failure's cause chain, reduced to what the StrongBox fallback decides on. */
internal sealed interface KeystoreFailureFact {
    /** `StrongBoxUnavailableException`: this device has no StrongBox for this key. */
    data object StrongBoxUnavailable : KeystoreFailureFact

    /** API 33+ `android.security.KeyStoreException`: its public error code and transient flag. */
    data class Coded(
        val numericErrorCode: Int,
        val transientFailure: Boolean,
    ) : KeystoreFailureFact

    /** A keystore exception before API 33, which publishes no code to read. */
    data object Unclassifiable : KeystoreFailureFact

    /** `InvalidAlgorithmParameterException`: the spec itself was refused. */
    data object SpecRejected : KeystoreFailureFact

    /** Any other link (a wrapping `ProviderException`, a `GeneralSecurityException`). */
    data object Wrapper : KeystoreFailureFact
}

/** What one refused StrongBox attempt leads to. */
internal sealed interface StrongBoxRefusal {
    /** StrongBox is busy or momentarily unreachable, and attempts remain: ask StrongBox again. */
    data object RetryStrongBox : StrongBoxRefusal

    /** Make the key in the TEE, recording why. */
    data class FallBackToTee(
        val fallback: SecureElementFallback.ToWeakerSecureTier,
    ) : StrongBoxRefusal
}

/** How many times a transient StrongBox refusal is retried before the key is made in the TEE. */
internal const val STRONGBOX_ATTEMPTS = 2

/**
 * Decides on refused StrongBox attempt number [attempt] (1-based) from its cause chain. A transient refusal is
 * tried again in StrongBox up to [STRONGBOX_ATTEMPTS] times, so a key is not settled in the TEE for life because
 * StrongBox was busy for a moment; after that, and for every other refusal, the key is made in the TEE, and the
 * fallback names the reason and the keystore's code.
 */
internal fun strongBoxRefusal(
    chain: List<KeystoreFailureFact>,
    attempt: Int,
): StrongBoxRefusal {
    val coded = chain.filterIsInstance<KeystoreFailureFact.Coded>().firstOrNull()
    val code =
        when (coded) {
            null -> AndroidKeystoreCode.Unpublished
            else -> AndroidKeystoreCode.Public(coded.numericErrorCode)
        }
    val transient = coded != null && coded.transientFailure
    if (transient && attempt < STRONGBOX_ATTEMPTS) return StrongBoxRefusal.RetryStrongBox
    val reason =
        when {
            KeystoreFailureFact.StrongBoxUnavailable in chain -> SecureElementFallbackReason.ElementAbsent
            transient -> SecureElementFallbackReason.ElementBusy
            coded == null && KeystoreFailureFact.SpecRejected in chain ->
                SecureElementFallbackReason.UnsupportedParameters
            coded == null -> SecureElementFallbackReason.Unclassified
            else -> reasonOfCode(coded.numericErrorCode)
        }
    return StrongBoxRefusal.FallBackToTee(
        SecureElementFallback.ToWeakerSecureTier(reason, AndroidKeystoreFallbackDetail(code)),
    )
}

private fun reasonOfCode(code: Int): SecureElementFallbackReason =
    when (code) {
        AndroidKeyStoreException.ERROR_UNIMPLEMENTED, AndroidKeyStoreException.ERROR_INCORRECT_USAGE ->
            SecureElementFallbackReason.UnsupportedParameters
        AndroidKeyStoreException.ERROR_KEYMINT_FAILURE, AndroidKeyStoreException.ERROR_INTERNAL_SYSTEM_ERROR ->
            SecureElementFallbackReason.ElementFailed
        else -> SecureElementFallbackReason.Unclassified
    }

/** The cause chain of [failure] as [KeystoreFailureFact]s, outermost first. */
internal fun keystoreFailureFacts(failure: Throwable): List<KeystoreFailureFact> {
    val facts = mutableListOf<KeystoreFailureFact>()
    var current: Throwable? = failure
    val seen = mutableSetOf<Throwable>()
    while (current != null && seen.add(current)) {
        facts +=
            when (current) {
                is StrongBoxUnavailableException -> KeystoreFailureFact.StrongBoxUnavailable
                is AndroidKeyStoreException ->
                    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
                        KeystoreFailureFact.Coded(current.numericErrorCode, current.isTransientFailure)
                    } else {
                        KeystoreFailureFact.Unclassifiable
                    }
                is InvalidAlgorithmParameterException -> KeystoreFailureFact.SpecRejected
                else -> KeystoreFailureFact.Wrapper
            }
        current = current.cause
    }
    return facts
}

/** The `KeyInfo` of an AndroidKeyStore [key] — a private key or a secret key. */
internal fun keyInfoOf(key: Key): KeyInfo =
    when (key) {
        is SecretKey ->
            SecretKeyFactory
                .getInstance(key.algorithm, ANDROID_KEY_STORE)
                .getKeySpec(key, KeyInfo::class.java) as KeyInfo
        else -> KeyFactory.getInstance(key.algorithm, ANDROID_KEY_STORE).getKeySpec(key, KeyInfo::class.java)
    }

/** Whether this runtime registers the `AndroidKeyStore` JCA provider at all (every device; no host JVM). */
internal fun androidKeystoreProviderRegistered(): Boolean = Security.getProvider(ANDROID_KEY_STORE) != null

/** The Android Keystore backend refused for [finding]. */
internal fun keystoreRefused(finding: CapabilityFinding.Keystore): ProtectedKeyResolution =
    ProtectedKeyResolution.Refused(ProtectedKeyBackend.AndroidKeystore, finding)
